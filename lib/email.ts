import { Resend } from "resend";
import type { FormInput, Plan } from "./schema";

const esc = (t: string) => t.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);

export function emailConfigured() {
  return Boolean(process.env.RESEND_API_KEY && process.env.EMAIL_FROM);
}

export async function sendPlanEmail(form: FormInput, plan: Plan, pdf: Buffer) {
  const resend = new Resend(process.env.RESEND_API_KEY);
  const firstName = form.fullName.split(/\s+/)[0];
  const wins = plan.quickWinsThisWeek.map((w) => `<li style="margin-bottom:6px">${esc(w)}</li>`).join("");
  const filename = `${form.businessName.replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "") || "SME"}-90-Day-AI-Plan.pdf`;

  const { error } = await resend.emails.send({
    from: process.env.EMAIL_FROM!,
    to: form.email,
    bcc: process.env.EMAIL_BCC || undefined,
    subject: `Your 90-Day AI Adoption Plan – ${form.businessName}`,
    html: `<div style="font-family:Arial,Helvetica,sans-serif;max-width:560px;margin:auto;color:#111">
  <div style="background:#111;color:#fff;padding:24px;border-radius:6px">
    <div style="color:#1FA9A1;font-size:12px;letter-spacing:1.5px;font-weight:bold">MEST AFRICA · AI FOR SMEs WORKSHOP</div>
    <h1 style="font-size:22px;margin:8px 0 0">${esc(plan.planTitle)}</h1>
  </div>
  <p>Hi ${esc(firstName)},</p>
  <p>Thank you for joining the <strong>AI for SMEs Workshop</strong>. Your personalised 90-day AI adoption plan for <strong>${esc(form.businessName)}</strong> is attached as a PDF.</p>
  <p><strong>Start with these quick wins this week:</strong></p>
  <ul>${wins}</ul>
  <p>Keep the plan somewhere handy and tick off each week as you go.</p>
  <p>To your growth,<br/>The MEST Africa team<br/><a href="https://meltwater.org" style="color:#1FA9A1">meltwater.org</a></p>
  <p style="font-size:11px;color:#5B6470">This plan was generated by AI from your workshop answers. Confirm tool prices before subscribing. Targets are goals, not guarantees.</p>
</div>`,
    attachments: [{ filename, content: pdf }],
  });
  if (error) throw new Error(`Email failed: ${error.message}`);
}
